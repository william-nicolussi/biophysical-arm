def load_comb_lut(path):
    """Load a combined LUT generated by generate_lut() as an xr.Dataset."""
    return xr.load_dataset(path)

def get_activation(angle, req_torque, W=None):
    """Interpolate the combined LUT at (W, angle, req_torque)."""
    W = CO_CONTR_W if W is None else W
    angle_lut = comb_lut.sel(W=W, method="nearest").interp(angle=angle)
    mint = float(angle_lut.torque_min)
    maxt = float(angle_lut.torque_max)
    torque_norm = (req_torque - mint) / (maxt - mint)
    activations = angle_lut.activation_value.interp(torque_norm=torque_norm).values
    return activations

def torque_norm_grid(n_points=61, edge_density=0.8):
    """Grid of torque_norm in [0, 1], denser near 0 and 1.
 
    edge_density = 0 -> uniform grid; closer to 1 -> more points at the edges.
    With n_points=61 and edge_density=0.8: step ~0.003 at the edges, ~0.03 in the middle.
    """
    s = np.linspace(0.0, 1.0, n_points)
    return s - edge_density * np.sin(2 * np.pi * s) / (2 * np.pi)

def build_comb_lut(W_values=None, torque_steps=TORQUE_STEPS, torque_norm=None):
    """Compute the combined LUT for every co-contraction weight in W_values.
 
    Returns an xr.Dataset with dims (W, angle, torque_norm, activation_idx) and variables:
      - activation_value (W, angle, torque_norm, activation_idx): optimal activations
      - torque (angle, torque_norm): absolute requested torque [Nm]
      - torque_min, torque_max (angle): torque limits at each angle (independent of W)
    torque = torque_min + torque_norm * (torque_max - torque_min)
 
    torque_norm: optional array in [0, 1] (e.g. torque_norm_grid()); if None, a uniform
    grid with torque_steps + 1 points is used.
    """
    W_values = np.atleast_1d(np.asarray(CO_CONTR_W if W_values is None else W_values, dtype=float))
    angles = lut.angle.values
    n_muscles = len(lut.muscle)
    max_a = np.append(np.zeros(3), np.ones(3))   # flexors at 1 -> torque_max
    min_a = np.append(np.ones(3), np.zeros(3))   # extensors at 1 -> torque_min
 
    if torque_norm is None:
        torque_norm = np.linspace(0, 1, torque_steps + 1)
    torque_norm = np.asarray(torque_norm, dtype=float)
    if torque_norm[0] != 0.0 or torque_norm[-1] != 1.0 or np.any(np.diff(torque_norm) <= 0):
        raise ValueError("torque_norm must be strictly increasing, from 0 to 1")
 
    torque_min = np.array([total_torque(min_a, angle) for angle in angles], dtype=float)
    torque_max = np.array([total_torque(max_a, angle) for angle in angles], dtype=float)
    torque = torque_min[:, None] + torque_norm[None, :] * (torque_max - torque_min)[:, None]
 
    data = np.zeros((len(W_values), len(angles), len(torque_norm), n_muscles))
    for w_idx, W in enumerate(tqdm(W_values, desc="W")):
        for a_idx, angle in enumerate(tqdm(angles, desc="angles", leave=False)):
            torque_fn = make_torque_fn(angle)        # LUT interpolated at this angle only once
            # the edges are known: only one activation pattern gives torque_min / torque_max
            data[w_idx, a_idx, 0] = min_a
            data[w_idx, a_idx, -1] = max_a
            x_prev = None
            for t_idx in range(1, len(torque_norm) - 1):
                x_prev = optimize_muscles_activation(angle, torque[a_idx, t_idx], W=W,
                                                     torque_fn=torque_fn, x0=x_prev)
                data[w_idx, a_idx, t_idx] = x_prev
 
    return xr.Dataset(
        data_vars=dict(
            activation_value=(["W", "angle", "torque_norm", "activation_idx"], data),
            torque=(["angle", "torque_norm"], torque),
            torque_min=(["angle"], torque_min),
            torque_max=(["angle"], torque_max),
        ),
        coords=dict(
            W=(["W"], W_values),
            angle=(["angle"], angles),
            torque_norm=(["torque_norm"], torque_norm),
            activation_idx=(["activation_idx"], np.arange(n_muscles)),
        ),
    )

def generate_lut(name, W_values=None, torque_steps=TORQUE_STEPS):
    comb_lut = build_comb_lut(W_values, torque_steps)
    output_path = os.path.join(MODELS_DIR, os.path.basename(name))
    # temporary file, otherwise on Windows it fails if the file is open
    temp_path = output_path + ".tmp"
    comb_lut.to_netcdf(temp_path)
    os.replace(temp_path, output_path)
    return comb_lut

