def total_torque(activations,angle):
    torque = 0
    for i, muscle in enumerate(lut.muscle.values):
        torque += lut.sel(muscle=muscle).interp(angle=angle, activation=activations[i]).values
    return torque

def make_torque_fn(angle):
    """Fast version of total_torque at a fixed angle.
 
    The forward LUT has only activation = 0 and 1 (ACT_STEPS = 1 in muscle_torque_map), and the
    torque of each muscle is linear in its activation (thesis, eq. 12). So, at a fixed angle,
    the total torque is affine in the activations:
 
        torque(a) = c0 + k . a,   c0 = sum_i tau_i(angle, 0),   k_i = tau_i(angle, 1) - tau_i(angle, 0)
 
    The LUT is interpolated in angle once; every evaluation is then a dot product.
    The returned function has the attribute .grad (= k, the constant gradient), used by SLSQP.
    """
    lut_a = lut.interp(angle=angle).transpose("muscle", "activation")
    act_grid = lut_a.activation.values
    tables = lut_a.values                      # (n_muscles, n_activation)
 
    if len(act_grid) == 2 and np.allclose(act_grid, [0.0, 1.0]):
        c0 = float(tables[:, 0].sum())
        k = tables[:, 1] - tables[:, 0]
 
        def torque_fn(activations):
            return c0 + float(np.dot(k, activations))
        torque_fn.grad = lambda activations: k
    else:
        # general case (more activation levels in the forward LUT): piecewise linear
        def torque_fn(activations):
            return float(sum(np.interp(activations[i], act_grid, tables[i]) for i in range(len(tables))))
        torque_fn.grad = None                  # SLSQP will use finite differences
    return torque_fn
  
def check_torque_fn(n_tests=200, seed=0):
    """Compare make_torque_fn with total_torque on random points. Run it once before generating."""
    rng = np.random.default_rng(seed)
    max_err = 0.0
    for _ in range(n_tests):
        angle = rng.uniform(lut.angle.values.min(), lut.angle.values.max())
        a = rng.uniform(0, 1, len(lut.muscle))
        max_err = max(max_err, abs(make_torque_fn(angle)(a) - float(total_torque(a, angle))))
    print(f"max |fast - original| = {max_err:.2e} Nm")
    return max_err

def optimize_muscles_activation(angle, req_torque, W=None, torque_fn=None, x0=None):
    """Optimal activations for (angle, req_torque).
 
    W: co-contraction weight (default CO_CONTR_W). torque_fn: from make_torque_fn(angle),
    pass it to avoid rebuilding it at every call. x0: warm start (e.g. the solution at the
    previous torque level); if None, starts from 0.5.
    """
    W = CO_CONTR_W if W is None else float(W)
    if torque_fn is None:
        torque_fn = make_torque_fn(angle)
 
    def objective(a):
        #effort = (1 - W) * np.sum(a**3) # Jiaing & Mirka -> ^3 (?)
        effort = (1 - W) * np.sum(a**2) # thesis eq. 10
        entropy = W * np.sum(a * np.log(a + 1e-9))
        return effort + entropy
 
    def objective_grad(a):
        # derivative of objective(): must be changed together with it
        #return 3 * (1 - W) * a**2 + W * (np.log(a + 1e-9) + a / (a + 1e-9)) # cube
        return 2 * (1 - W) * a + W * (np.log(a + 1e-9) + a / (a + 1e-9)) # square
 
    constraint = {"type": "eq", "fun": lambda a: torque_fn(a) - req_torque}
    if getattr(torque_fn, "grad", None) is not None:
        constraint["jac"] = torque_fn.grad     # exact gradient: no finite differences
    bounds = [(0, 1)] * len(lut.muscle)
 
    def solve(start):
        # "SLSQP" = Sequential Least Squares Quadratic
        return minimize(objective, x0=start, jac=objective_grad, method="SLSQP",
                        constraints=constraint, bounds=bounds, options={"ftol": 1e-10, "maxiter": 300})
 
    candidates = [solve(np.full(len(lut.muscle), 0.5))]
    if x0 is not None:
        # warm start, kept slightly inside the bounds (the gradient of a*log(a) is huge at 0)
        candidates.append(solve(np.clip(x0, 0.01, 0.99)))
 
    # keep the feasible solution with the lowest cost
    def score(r):
        feasible = abs(torque_fn(r.x) - req_torque) < 1e-4
        return (not feasible, r.fun)
    best = min(candidates, key=score)
    if abs(torque_fn(best.x) - req_torque) > 1e-4:
        print(f"Warning: angle {angle:.1f}, torque {req_torque:.3f} Nm: constraint not satisfied "
              f"({best.message})")
    return np.clip(best.x, 0.0, 1.0)

